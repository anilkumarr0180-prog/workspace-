/**
 * Workspace — Local Email Transport Verification Script
 * Validates:
 * 1. Server-side environment configuration loading
 * 2. Mailpit SMTP connection handshake (verifyLocalSmtpConnection)
 * 3. Nodemailer single test email dispatch to fixed local address (test@workspace.local)
 * 4. Mailpit REST API automated verification (http://127.0.0.1:54324/api/v1/messages)
 */

import fs from 'fs';
import path from 'path';

// 1. Manually load .env.local if running in standalone script execution
const envLocalPath = path.join(process.cwd(), '.env.local');
if (fs.existsSync(envLocalPath)) {
  const content = fs.readFileSync(envLocalPath, 'utf8');
  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      if (!process.env[key]) {
        process.env[key] = val;
      }
    }
  }
}

// Ensure development environment flag
const currentEnv = process.env.NODE_ENV || 'development';
Object.assign(process.env, { NODE_ENV: currentEnv });

import { verifyLocalSmtpConnection, sendLocalEmail } from '../lib/email/local-transporter';

const FIXED_TEST_RECIPIENT = 'test@workspace.local';
const MAILPIT_API_URL = 'http://127.0.0.1:54324/api/v1';

async function runLocalEmailVerification() {
  console.log('===============================================================');
  console.log('WORKSPACE — STEP 1C: LOCAL MAILPIT EMAIL VERIFICATION');
  console.log('===============================================================\n');

  // Guard: strictly prohibit running against anything other than local development
  if (process.env.NODE_ENV !== 'development' && process.env.NODE_ENV !== 'test') {
    throw new Error('Safety guard: Test script can only be executed in development mode.');
  }

  const host = process.env.LOCAL_SMTP_HOST || '127.0.0.1';
  const port = process.env.LOCAL_SMTP_PORT || '54325';
  console.log(`[1/4] Verifying Local SMTP Connection (${host}:${port})...`);
  const connResult = await verifyLocalSmtpConnection();
  if (!connResult.success) {
    throw new Error(`SMTP connection check failed: ${connResult.error}`);
  }
  console.log('  ✓ SMTP connection to Mailpit verified successfully.\n');

  const testId = Date.now();
  const testSubject = `Workspace Test Notification #${testId}`;
  const testBody = `Hello! This is a test email sent from Workspace via local Nodemailer transport.\nTimestamp: ${new Date().toISOString()}\nTest ID: ${testId}`;
  const testHtml = `<div style="font-family: sans-serif; padding: 20px;">
    <h2>Workspace Local Email Test</h2>
    <p>This is a test notification generated by <strong>Workspace</strong> local email transport.</p>
    <p><strong>Test ID:</strong> ${testId}</p>
    <p><strong>Time:</strong> ${new Date().toISOString()}</p>
  </div>`;

  console.log(`[2/4] Sending test email to fixed recipient: ${FIXED_TEST_RECIPIENT}...`);
  const sendResult = await sendLocalEmail({
    to: FIXED_TEST_RECIPIENT,
    subject: testSubject,
    text: testBody,
    html: testHtml,
  });

  if (!sendResult.success || !sendResult.messageId) {
    throw new Error(`Failed to send test email: ${sendResult.error}`);
  }

  console.log(`  ✓ Email accepted by SMTP server.`);
  console.log(`  ✓ Message ID: ${sendResult.messageId}`);
  console.log(`  ✓ Accepted: ${JSON.stringify(sendResult.accepted)}`);
  console.log(`  ✓ SMTP Response: ${sendResult.response}\n`);

  console.log(`[3/4] Verifying message arrival in Mailpit REST API (${MAILPIT_API_URL}/messages)...`);
  // Small wait for Mailpit SQLite persistence
  await new Promise((resolve) => setTimeout(resolve, 500));

  const listRes = await fetch(`${MAILPIT_API_URL}/messages`);
  if (!listRes.ok) {
    throw new Error(`Mailpit API returned status ${listRes.status}: ${listRes.statusText}`);
  }

  const listData = await listRes.json();
  const messages: Array<{
    ID: string;
    Subject: string;
    From: { Address: string; Name: string };
    To: Array<{ Address: string; Name: string }>;
    Created: string;
  }> = listData.messages || [];

  const found = messages.find((m) => m.Subject === testSubject);
  if (!found) {
    throw new Error(`Test email "${testSubject}" was not found in Mailpit! Total messages in Mailpit: ${messages.length}`);
  }

  console.log(`  ✓ Message confirmed in Mailpit!`);
  console.log(`  ✓ Mailpit ID: ${found.ID}`);
  console.log(`  ✓ Subject: ${found.Subject}`);
  console.log(`  ✓ From: ${found.From.Name} <${found.From.Address}>`);
  console.log(`  ✓ To: ${found.To.map((t) => t.Address).join(', ')}`);

  console.log('\n[4/4] Verifying message body contents from Mailpit...');
  const detailRes = await fetch(`${MAILPIT_API_URL}/message/${found.ID}`);
  if (!detailRes.ok) {
    throw new Error(`Failed to fetch Mailpit message details: ${detailRes.statusText}`);
  }
  const detailData = await detailRes.json();

  if (!detailData.Text?.includes(String(testId)) || !detailData.HTML?.includes(String(testId))) {
    throw new Error('Message body content mismatch in Mailpit.');
  }
  console.log('  ✓ Text body verified with unique test token.');
  console.log('  ✓ HTML body verified with unique test token.');

  console.log('\n===============================================================');
  console.log('SUCCESS: LOCAL NODEMAILER & MAILPIT VERIFIED END-TO-END!');
  console.log('===============================================================\n');
}

runLocalEmailVerification().catch((err) => {
  console.error('\nVerification FAILED:', err);
  process.exit(1);
});
